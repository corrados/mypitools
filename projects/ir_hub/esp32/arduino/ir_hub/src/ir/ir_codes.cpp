const char* device_name(Device device) {
    switch (device) {
        case Device::Bar:
            return "BAR";
        case Device::Beam:
            return "BEAM";
        case Device::Led:
            return "LED";
        case Device::Tv:
            return "TV";
        case Device::Dvd:
            return "DVD";
        case Device::FireTvBeam:
            return "FIRETVBEAM";
        case Device::Unknown:
            return "UNKNOWN";
    }
    return "UNKNOWN";
}

bool find_code(Device device, const char* command, const char*& code) {
    if (command == nullptr) {
        return false;
    }

    switch (device) {
        case Device::Bar:
            return find_in(kBarCodes, command, code);
        case Device::Beam:
            return find_in(kBeamCodes, command, code);
        case Device::Led:
            return find_in(kLedCodes, command, code);
        case Device::Tv:
            return find_in(kTvCodes, command, code);
        case Device::Dvd:
            return find_in(kDvdCodes, command, code);
        case Device::FireTvBeam:
        case Device::Unknown:
            return false;
    }
    return false;
}

