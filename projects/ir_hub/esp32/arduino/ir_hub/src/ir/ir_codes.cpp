template <size_t N>
bool find_in(const CodeEntry (&table)[N], const char* command, const char*& code) {
    for (size_t i = 0; i < N; ++i) {
        if (std::strcmp(table[i].command, command) == 0) {
            code = table[i].code;
            return true;
        }
    }
    return false;
}

